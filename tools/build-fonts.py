"""
Builds the self-hosted fonts for the website and the dashboard:

  fonts/montserrat-latin.woff2, fonts/raleway-latin.woff2   (text fonts, from Google Fonts)
  fonts/fa-solid.woff2, fonts/fa-regular.woff2, fonts/fa-brands.woff2
                                                            (Font Awesome 6.5.1 Free, only the icons we use)
  css/fonts.css                                             (@font-face rules + Font Awesome classes)

Serving these from our own server removes two slow outside requests that blocked every page,
and the icon fonts shrink from ~270 KB to a few KB.

Run it again after using a NEW icon anywhere (fa-something):   python tools/build-fonts.py
Needs: pip install fonttools brotli
"""
import io
import os
import re
import sys
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FA = 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.1'
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'
GOOGLE = 'https://fonts.googleapis.com/css2?family=Montserrat:wght@400;500;600;700;800&family=Raleway:wght@300;400;500;600;700&display=swap'


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def used_icon_names() -> set:
    names = set()
    for dirpath, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in ('.git', 'uploads', 'node_modules', 'tools', 'fonts')]
        for f in files:
            if f.endswith(('.html', '.php', '.js')):
                text = open(os.path.join(dirpath, f), encoding='utf-8', errors='ignore').read()
                names.update(re.findall(r'(?<![\w-])fa-[a-z0-9]+(?:-[a-z0-9]+)*', text))
    return names


def main() -> None:
    os.makedirs(os.path.join(ROOT, 'fonts'), exist_ok=True)

    # ---- Font Awesome: keep only the icon rules we use, subset the fonts to those glyphs ----
    css = get(FA + '/css/all.min.css').decode('utf-8')
    used = used_icon_names()
    keep_codes = set()

    def keep_rule(m):
        selectors = re.findall(r'\.(fa-[a-z0-9-]+):before', m.group(1))
        mine = [s for s in selectors if s in used]
        if not mine:
            return ''
        keep_codes.add(int(m.group(2), 16))
        return ','.join('.' + s + ':before' for s in mine) + '{content:"\\' + m.group(2) + '"}'

    css = re.sub(r'((?:\.fa-[a-z0-9-]+:before,?)+)\{content:"\\([0-9a-f]+)"\}', keep_rule, css)
    # Drop the Font Awesome 4/5 compatibility fonts; we only use v6 class names
    css = re.sub(r'@font-face\{font-family:"?(FontAwesome|Font Awesome 5[^"]*)"?;[^}]*\}', '', css)
    sizes = {}
    for style, src in [('solid', 'fa-solid-900'), ('regular', 'fa-regular-400'), ('brands', 'fa-brands-400')]:
        font = TTFont(io.BytesIO(get(f'{FA}/webfonts/{src}.ttf')))
        have = set(font.getBestCmap().keys())
        codes = sorted(keep_codes & have)
        out = os.path.join(ROOT, 'fonts', f'fa-{style}.woff2')
        if codes:
            opts = subset.Options()
            opts.flavor = 'woff2'
            opts.layout_features = ['*']
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=codes)
            sub.subset(font)
            font.flavor = 'woff2'
            font.save(out)
            sizes[style] = (len(codes), os.path.getsize(out))
        css = re.sub(r'url\(\.\./webfonts/' + src + r'\.woff2\) format\("woff2"\),url\(\.\./webfonts/' + src + r'\.ttf\) format\("truetype"\)',
                     f'url(../fonts/fa-{style}.woff2) format("woff2")', css)
    if '../webfonts/' in css:
        sys.exit('Unexpected Font Awesome CSS format; check the @font-face rules.')

    # ---- Text fonts: the latin files of the Montserrat and Raleway variable fonts ----
    gcss = get(GOOGLE).decode('utf-8')
    text_faces = []
    for family in ('Montserrat', 'Raleway'):
        m = re.search(r"/\* latin \*/\s*@font-face \{[^}]*font-family: '" + family + r"';[^}]*src: url\(([^)]+)\)[^}]*unicode-range: ([^;]+);", gcss)
        if not m:
            sys.exit(f'Could not find the latin {family} font in the Google Fonts CSS.')
        fname = f'{family.lower()}-latin.woff2'
        with open(os.path.join(ROOT, 'fonts', fname), 'wb') as fh:
            fh.write(get(m.group(1)))
        text_faces.append(
            f"@font-face{{font-family:'{family}';font-style:normal;font-weight:300 800;font-display:swap;"
            f"src:url(../fonts/{fname}) format('woff2');unicode-range:{m.group(2)}}}"
        )

    header = '/* Generated by tools/build-fonts.py - do not edit. Font Awesome Free 6.5.1 (fontawesome.com, license: fontawesome.com/license/free); Montserrat and Raleway (SIL Open Font License). */\n'
    with open(os.path.join(ROOT, 'css', 'fonts.css'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(header + '\n'.join(text_faces) + '\n' + css + '\n')

    print(f'{len(keep_codes)} icons kept')
    for style, (n, size) in sizes.items():
        print(f'  fa-{style}.woff2: {n} glyphs, {size // 1024} KB')
    print(f'  css/fonts.css: {os.path.getsize(os.path.join(ROOT, "css", "fonts.css")) // 1024} KB')


if __name__ == '__main__':
    main()
